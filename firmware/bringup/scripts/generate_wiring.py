#!/usr/bin/env python3
"""Generate firmware pins + readable wiring data from one reviewed manifest."""
import csv
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def load_and_validate():
    data = json.loads((ROOT / "wiring.json").read_text())
    reference = (ROOT / data["screen_source"]).resolve()
    snapshot = ROOT / "docs/reference/revb-screen-interface.json"
    if not reference.exists():
        reference = snapshot
    source = json.loads(reference.read_text())
    assert data["screen"]["voltage_v"] == source["supply"]["voltage_v"] == 3.3
    assert [p["pin"] for p in data["screen"]["pins"]] == list(range(1, 13))
    for a, b in zip(data["screen"]["pins"], source["pins"]):
        assert a["pin"] == b["module_pin"]
        assert a["label"] == b["module_signal"]
        actual = ("GPIO" + str(a["gpio"])) if a["gpio"] is not None else ("GND" if a["kind"] == "ground" else "LCD_3V3")
        assert actual == b["mcu_or_power"], (a, b)
    gpios = [p["gpio"] for p in data["screen"]["pins"] if p["gpio"] is not None]
    gpios += [p["gpio"] for p in data["mic"]["pins"] if p["gpio"] is not None]
    gpios += [data["servo"]["gpio"], data["onboard"]["led_gpio"], data["onboard"]["boot_gpio"]]
    assert len(gpios) == len(set(gpios)), "GPIO conflict"
    assert not set(gpios) & ({3, 19, 20, 43, 44, 45, 46} | set(range(26, 38))), "Reserved GPIO used"
    assert data["servo"]["minimum_us"] < data["servo"]["center_us"] < data["servo"]["maximum_us"]
    assert data["mic"]["supply_v"] == 3.3
    assert data["mic"]["data_bits"] < data["mic"]["slot_bits"], "I2S data must sit inside a wider slot"
    assert [p["pin"] for p in data["mic"]["pins"]] == list(range(1, 7))
    assert {"MIC_BCLK", "MIC_WS", "MIC_SD"} <= {p["key"] for p in data["mic"]["pins"]}
    assert all(p["gpio"] is not None for p in data["mic"]["pins"] if p["kind"] == "i2s")
    lr = [p for p in data["mic"]["pins"] if p["key"] == "MIC_LR"]
    assert len(lr) == 1 and lr[0]["kind"] == "ground", "L/R must be strapped to GND for the left channel"
    snapshot.parent.mkdir(parents=True, exist_ok=True)
    if reference != snapshot:
        snapshot.write_text(json.dumps(source, ensure_ascii=False, indent=2) + "\n")
    pin_source = ROOT / "../../pcb-design/rev-a/01-controller-pinout.csv"
    pin_snapshot = ROOT / "docs/reference/lckfb-pin-locations.csv"
    if pin_source.exists():
        with pin_source.open(encoding="utf-8-sig", newline="") as f:
            positions = list(csv.DictReader(f))
        with pin_snapshot.open("w", encoding="utf-8-sig", newline="") as f:
            fields = ["本项目位置", "厂家原理图针号", "厂家丝印"]
            w = csv.DictWriter(f, fieldnames=fields, extrasaction="ignore")
            w.writeheader()
            w.writerows(positions)
    else:
        with pin_snapshot.open(encoding="utf-8-sig", newline="") as f:
            positions = list(csv.DictReader(f))
    index = {r["本项目位置"]: r["厂家丝印"] for r in positions}
    for pin in data["screen"]["pins"]:
        if pin["gpio"] is not None:
            assert index[pin["position"]] == "GPIO" + str(pin["gpio"])
    for pin in data["mic"]["pins"]:
        if pin["gpio"] is not None:
            assert index[pin["position"]] == "GPIO" + str(pin["gpio"])
    for suffix in ("", "2"):
        if data["servo"].get("gpio" + suffix) is not None:
            assert index[data["servo"]["position" + suffix]] == "GPIO" + str(data["servo"]["gpio" + suffix])
    assert index["L7"] == index["R9"] == "GND"
    return data, positions


def generate(data):
    (ROOT / "include").mkdir(exist_ok=True)
    (ROOT / "docs").mkdir(exist_ok=True)
    lines = ["// Generated by scripts/generate_wiring.py from wiring.json. Do not edit.", "#pragma once", "#include <cstdint>", "namespace config {"]
    for p in data["screen"]["pins"]:
        if p["gpio"] is not None:
            lines.append(f'constexpr int {p["key"]} = {p["gpio"]};')
    for key, value in data["servo"].items():
        if isinstance(value, int):
            lines.append(f'constexpr uint32_t SERVO_{key.upper()} = {value}u;')
    for p in data["mic"]["pins"]:
        if p["gpio"] is not None:
            lines.append(f'constexpr int {p["key"]} = {p["gpio"]};')
    for key in ("sample_rate_hz", "slot_bits", "data_bits"):
        lines.append(f'constexpr uint32_t MIC_{key.upper()} = {data["mic"][key]}u;')
    for key, value in data["onboard"].items():
        if isinstance(value, bool):
            lines.append(f'constexpr bool {key.upper()} = {str(value).lower()};')
        else:
            lines.append(f'constexpr int {key.upper()} = {value};')
    for key in ("width", "height", "rotation", "spi_hz", "encoder_transitions_per_detent"):
        lines.append(f'constexpr uint32_t SCREEN_{key.upper()} = {data["screen"][key]}u;')
    lines.append(f'constexpr bool SCREEN_INVERTED = {str(data["screen"]["inverted"]).lower()};')
    lines.append("} // namespace config\n")
    (ROOT / "include/board_config.h").write_text("\n".join(lines))
    with (ROOT / "docs/屏幕12针接线表.csv").open("w", encoding="utf-8-sig", newline="") as f:
        w = csv.writer(f)
        w.writerow(["模块针号", "模块丝印", "接到哪里", "开发板位置", "用途"])
        for p in data["screen"]["pins"]:
            w.writerow([p["pin"], p["label"], p["target"], p["position"], {"ground":"共地", "power":"仅外部3.3V", "spi":"SPI信号", "input":"3.3V控件输入，模块自带上拉"}[p["kind"]]])
    with (ROOT / "docs/麦克风6针接线表.csv").open("w", encoding="utf-8-sig", newline="") as f:
        w = csv.writer(f)
        w.writerow(["模块针号", "模块丝印", "接到哪里", "开发板位置", "用途"])
        for p in data["mic"]["pins"]:
            w.writerow([p["pin"], p["label"], p["target"], p["position"], {"ground":"共地", "power":"3.3V供电", "i2s":"I2S信号"}[p["kind"]]])


if __name__ == "__main__":
    wiring, positions = load_and_validate()
    generate(wiring)
    from render_docs import render_docs
    render_docs(ROOT, wiring, positions)
    print("PASS: 12 display pins match RevB; board positions and reserved GPIOs checked.")
